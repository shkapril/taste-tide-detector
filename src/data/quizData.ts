export interface TasteProfile {
  level: number;
  label: string;
  description: string;
  emoji: string;
  percentile: number;
}

export const getTasteProfile = (averageLevel: number, quizType: QuizType): TasteProfile => {
  const labels = quizLabels[quizType];
  
  if (averageLevel <= 2) {
    return {
      level: averageLevel,
      label: `${labels.lowLabel} Lover`,
      description: `You prefer subtle ${labels.label.toLowerCase()} levels. You appreciate understated flavors!`,
      emoji: '🌿',
      percentile: 15,
    };
  } else if (averageLevel <= 4) {
    return {
      level: averageLevel,
      label: `Mild ${labels.label}`,
      description: `You enjoy gentle ${labels.label.toLowerCase()}. Balance is key for you.`,
      emoji: '⚖️',
      percentile: 30,
    };
  } else if (averageLevel <= 6) {
    return {
      level: averageLevel,
      label: 'Balanced Palate',
      description: `You enjoy moderate ${labels.label.toLowerCase()} - not too mild, not too intense!`,
      emoji: '👌',
      percentile: 50,
    };
  } else if (averageLevel <= 8) {
    return {
      level: averageLevel,
      label: `${labels.label} Enthusiast`,
      description: `You embrace ${labels.label.toLowerCase()} with open arms. More is better!`,
      emoji: '🔥',
      percentile: 75,
    };
  } else {
    return {
      level: averageLevel,
      label: `${labels.label} Maximalist`,
      description: `Go big or go home! You love intense ${labels.label.toLowerCase()}.`,
      emoji: '🚀',
      percentile: 95,
    };
  }
};

